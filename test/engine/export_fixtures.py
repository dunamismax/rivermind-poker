"""Export the rule hands in ``fixtures.py`` to JSON for the TypeScript engine (P4B.4).

Run ``uv run --locked python -m test.engine.export_fixtures`` from the
repository root to rewrite ``web/src/lib/server/engine/rules.json``;
``test_export_fixtures.py`` fails when the committed file is stale. Each hand
keeps its hand-worked expectations (final stacks, pots, uncalled bet, shown
and mucked seats) and adds the Python engine's final state document and text
history, which the TypeScript engine must reproduce byte for byte.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from rivermind.engine.history import dumps, format_text, hand_record, state_to_dict

from .fixtures import FIXTURES, Fixture
from .helpers import deal, play

OUTPUT = Path(__file__).resolve().parents[2] / "web" / "src" / "lib" / "server" / "engine" / "rules.json"


def fixture_doc(fixture: Fixture) -> dict[str, Any]:
    state = play(
        deal(fixture.stacks, fixture.button, fixture.holes, fixture.board, fixture.config),
        fixture.script,
    )
    return {
        "name": fixture.name,
        "rule": fixture.rule,
        "config": {
            "small_blind": fixture.config.small_blind,
            "big_blind": fixture.config.big_blind,
            "ante": fixture.config.ante,
        },
        "stacks": list(fixture.stacks),
        "button": fixture.button,
        "holes": {str(seat): text for seat, text in sorted(fixture.holes.items())},
        "board": fixture.board,
        "script": fixture.script,
        "final": list(fixture.final),
        "pots": None if fixture.pots is None else [[amount, list(winners)] for amount, winners in fixture.pots],
        "uncalled": None if fixture.uncalled is None else list(fixture.uncalled),
        "shown": None if fixture.shown is None else list(fixture.shown),
        "mucked": None if fixture.mucked is None else list(fixture.mucked),
        "tabled": fixture.tabled,
        "reference": {
            "record": dumps(hand_record(state)),
            "state": dumps(state_to_dict(state)),
            "text": format_text(state),
        },
    }


def export() -> str:
    """The JSON text of every fixture."""
    document = {
        "note": "Generated by test/engine/export_fixtures.py from test/engine/fixtures.py. Do not edit.",
        "fixtures": [fixture_doc(f) for f in FIXTURES],
    }
    return json.dumps(document, indent="\t", ensure_ascii=False) + "\n"


def main() -> int:
    OUTPUT.write_text(export(), encoding="utf-8")
    print(f"wrote {len(FIXTURES)} fixtures to {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
