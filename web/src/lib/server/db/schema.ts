/**
 * The site database, as Alembic head `0006` left it (P4B.3).
 *
 * Started from `drizzle-kit pull` against a database migrated by
 * `rivermind/db` and cleaned up by hand; the baseline migration in
 * `web/drizzle/` creates exactly this schema, which `pnpm db:compare` checks.
 * Names follow the Alembic naming convention (`pk_<table>`, `fk_<table>_<column>_<referred>`,
 * `ix_<table>_<column>`, `uq_…`, `ck_<table>_<name>`), and the columns of each table are in
 * their order in the database, since later migrations appended some of them.
 *
 * Tables are unqualified, as Alembic's are: they live in the first schema on
 * the connection's `search_path`, which is `app` for the site's roles on
 * ubuntu-vm (`deploy/setup-database.sh`) and `public` locally and in CI.
 *
 * Chips are whole numbers in `bigint` columns, read as JavaScript numbers:
 * every amount is far below 2^53. Table state and hand histories are the
 * versioned JSON documents of the engine's history module. Each player's
 * balance changes only together with a row in `ledger_entries` (D-1: the
 * chips have no cash value).
 */
import { sql } from 'drizzle-orm';
import {
	bigint,
	boolean,
	check,
	foreignKey,
	index,
	integer,
	jsonb,
	pgTable,
	primaryKey,
	smallint,
	text,
	timestamp,
	unique,
	varchar
} from 'drizzle-orm/pg-core';

/** A whole number of chips, or another `bigint` that stays below 2^53. */
const chips = (name: string) => bigint(name, { mode: 'number' });

/** A `timestamp with time zone` column. */
const stamp = (name: string) => timestamp(name, { withTimezone: true, mode: 'date' });

/** When the row was made, set by the database. */
const now = (name: string) => stamp(name).defaultNow().notNull();

/** A `bigint` identity key, `GENERATED BY DEFAULT AS IDENTITY` as Alembic's `Identity()` makes it. */
const identity = (name: string) => chips(name).generatedByDefaultAsIdentity();

/** The ledger's kinds of balance change (P4.2). Grants, top-ups, cash-outs and refunds add chips. */
export const LEDGER_KINDS = ['grant', 'top_up', 'buy_in', 'rebuy', 'cash_out', 'refund'] as const;
export type LedgerKind = (typeof LEDGER_KINDS)[number];

/** Why one player reported another (P4.5); `voice` is something said in table voice (P4C.8). */
export const REPORT_REASONS = ['handle', 'abuse', 'collusion', 'other', 'voice'] as const;
export type ReportReason = (typeof REPORT_REASONS)[number];

/** An anonymous player, made on their first visit (P4.1). Their session cookie is signed by the server, so no session rows are stored. */
export const players = pgTable(
	'players',
	{
		id: varchar('id', { length: 64 }).notNull(),
		handle: text('handle').notNull(),
		createdAt: now('created_at'),
		lastSeenAt: now('last_seen_at'),
		balance: chips('balance')
			.default(sql`'0'`)
			.notNull(),
		/** When the starting grant or the last daily top-up was paid. */
		grantedAt: stamp('granted_at')
	},
	(t) => [
		primaryKey({ name: 'pk_players', columns: [t.id] }),
		unique('uq_players_handle').on(t.handle),
		check('ck_players_handle', sql`char_length(handle) BETWEEN 1 AND 32`),
		check('ck_players_balance', sql`balance >= 0`)
	]
);

/** One change to a player's play-chip balance (P4.2). The entries always add up to the balance. */
export const ledgerEntries = pgTable(
	'ledger_entries',
	{
		id: identity('id'),
		playerId: varchar('player_id', { length: 64 }).notNull(),
		kind: varchar('kind', { length: 16 }).$type<LedgerKind>().notNull(),
		amount: chips('amount').notNull(),
		balanceAfter: chips('balance_after').notNull(),
		tableId: varchar('table_id', { length: 64 }),
		createdAt: now('created_at')
	},
	(t) => [
		primaryKey({ name: 'pk_ledger_entries', columns: [t.id] }),
		foreignKey({
			name: 'fk_ledger_entries_player_id_players',
			columns: [t.playerId],
			foreignColumns: [players.id]
		}).onDelete('cascade'),
		index('ix_ledger_entries_player_id').on(t.playerId),
		check(
			'ck_ledger_entries_kind',
			sql`kind IN ('grant', 'top_up', 'buy_in', 'rebuy', 'cash_out', 'refund')`
		),
		check('ck_ledger_entries_amount', sql`amount <> 0`),
		check('ck_ledger_entries_balance_after', sql`balance_after >= 0`),
		check(
			'ck_ledger_entries_direction',
			sql`(kind IN ('grant', 'top_up', 'cash_out', 'refund')) = (amount > 0)`
		)
	]
);

/** One player reporting another, for review (P4.5). */
export const playerReports = pgTable(
	'player_reports',
	{
		id: identity('id'),
		reporterId: varchar('reporter_id', { length: 64 }).notNull(),
		targetId: varchar('target_id', { length: 64 }).notNull(),
		/** The handle when reported, which a rename may change. */
		targetHandle: text('target_handle').notNull(),
		reason: varchar('reason', { length: 16 }).$type<ReportReason>().notNull(),
		tableId: varchar('table_id', { length: 64 }),
		handNo: integer('hand_no'),
		status: varchar('status', { length: 16 })
			.$type<'open' | 'reviewed'>()
			.default('open')
			.notNull(),
		createdAt: now('created_at'),
		/** The reporter's address as a keyed hash (`addressTag`), never the address (P4C.8). */
		reporterAddress: varchar('reporter_address', { length: 24 })
	},
	(t) => [
		primaryKey({ name: 'pk_player_reports', columns: [t.id] }),
		foreignKey({
			name: 'fk_player_reports_reporter_id_players',
			columns: [t.reporterId],
			foreignColumns: [players.id]
		}).onDelete('cascade'),
		foreignKey({
			name: 'fk_player_reports_target_id_players',
			columns: [t.targetId],
			foreignColumns: [players.id]
		}).onDelete('cascade'),
		index('ix_player_reports_reporter_id').on(t.reporterId),
		index('ix_player_reports_target_id').on(t.targetId),
		check(
			'ck_player_reports_reason',
			sql`reason IN ('handle', 'abuse', 'collusion', 'other', 'voice')`
		),
		check('ck_player_reports_status', sql`status IN ('open', 'reviewed')`),
		check('ck_player_reports_not_self', sql`reporter_id <> target_id`)
	]
);

/** A player muting or blocking another (P4.5). */
export const playerRelations = pgTable(
	'player_relations',
	{
		playerId: varchar('player_id', { length: 64 }).notNull(),
		targetId: varchar('target_id', { length: 64 }).notNull(),
		kind: varchar('kind', { length: 16 }).$type<'mute' | 'block'>().notNull(),
		createdAt: now('created_at')
	},
	(t) => [
		primaryKey({ name: 'pk_player_relations', columns: [t.playerId, t.targetId] }),
		foreignKey({
			name: 'fk_player_relations_player_id_players',
			columns: [t.playerId],
			foreignColumns: [players.id]
		}).onDelete('cascade'),
		foreignKey({
			name: 'fk_player_relations_target_id_players',
			columns: [t.targetId],
			foreignColumns: [players.id]
		}).onDelete('cascade'),
		index('ix_player_relations_target_id').on(t.targetId),
		check('ck_player_relations_kind', sql`kind IN ('mute', 'block')`),
		check('ck_player_relations_not_self', sql`player_id <> target_id`)
	]
);

/**
 * Something worth reviewing for collusion, such as two people at a table from
 * one address (P4.5). Signals hold keyed hashes of network addresses, never the addresses.
 */
export const safetySignals = pgTable(
	'safety_signals',
	{
		id: identity('id'),
		kind: varchar('kind', { length: 32 }).$type<'same_address'>().notNull(),
		tableId: varchar('table_id', { length: 64 }),
		playerIds: jsonb('player_ids').$type<string[]>().notNull(),
		detail: jsonb('detail').$type<Record<string, unknown>>().default({}).notNull(),
		createdAt: now('created_at')
	},
	(t) => [
		primaryKey({ name: 'pk_safety_signals', columns: [t.id] }),
		check('ck_safety_signals_kind', sql`kind IN ('same_address')`)
	]
);

/**
 * A guest whose speaking in table voice is suspended (P4C.8), after voice
 * reports from three people at three tables from three addresses within a
 * day. Until `until` the voice service refuses their audio; they may still listen.
 */
export const voiceSuspensions = pgTable(
	'voice_suspensions',
	{
		playerId: varchar('player_id', { length: 64 }).notNull(),
		until: stamp('until').notNull(),
		createdAt: now('created_at')
	},
	(t) => [
		primaryKey({ name: 'pk_voice_suspensions', columns: [t.playerId] }),
		foreignKey({
			name: 'fk_voice_suspensions_player_id_players',
			columns: [t.playerId],
			foreignColumns: [players.id]
		}).onDelete('cascade')
	]
);

/** A table's configuration and its saved state (P3.5). */
export const pokerTables = pgTable(
	'poker_tables',
	{
		id: varchar('id', { length: 64 }).notNull(),
		name: text('name').notNull(),
		seatCount: smallint('seat_count').notNull(),
		smallBlind: chips('small_blind').notNull(),
		bigBlind: chips('big_blind').notNull(),
		ante: chips('ante')
			.default(sql`'0'`)
			.notNull(),
		minBuyIn: chips('min_buy_in').notNull(),
		maxBuyIn: chips('max_buy_in').notNull(),
		status: varchar('status', { length: 16 }).$type<'open' | 'closed'>().default('open').notNull(),
		/** The table snapshot, a versioned JSON document, with its format number beside it. */
		state: jsonb('state').$type<Record<string, unknown>>(),
		stateFormat: integer('state_format'),
		createdAt: now('created_at'),
		updatedAt: now('updated_at'),
		/** A guest's practice table (P6.0b): no wallet chips, and its hands stay out of competitive stats. */
		practice: boolean('practice').default(false).notNull()
	},
	(t) => [
		primaryKey({ name: 'pk_poker_tables', columns: [t.id] }),
		check('ck_poker_tables_seat_count', sql`seat_count BETWEEN 2 AND 9`),
		check('ck_poker_tables_blinds', sql`small_blind > 0 AND big_blind >= small_blind`),
		check('ck_poker_tables_ante', sql`ante >= 0`),
		check('ck_poker_tables_buy_in', sql`min_buy_in > 0 AND max_buy_in >= min_buy_in`),
		check('ck_poker_tables_status', sql`status IN ('open', 'closed')`),
		check('ck_poker_tables_state_format', sql`(state IS NULL) = (state_format IS NULL)`)
	]
);

/** An occupied seat. Empty seats have no row. */
export const seats = pgTable(
	'seats',
	{
		tableId: varchar('table_id', { length: 64 }).notNull(),
		seatNo: smallint('seat_no').notNull(),
		displayName: text('display_name').notNull(),
		isBot: boolean('is_bot').notNull(),
		botKind: varchar('bot_kind', { length: 64 }),
		stack: chips('stack').notNull(),
		sittingOut: boolean('sitting_out').default(false).notNull(),
		joinedAt: now('joined_at')
	},
	(t) => [
		primaryKey({ name: 'pk_seats', columns: [t.tableId, t.seatNo] }),
		foreignKey({
			name: 'fk_seats_table_id_poker_tables',
			columns: [t.tableId],
			foreignColumns: [pokerTables.id]
		}).onDelete('cascade'),
		check('ck_seats_seat_no', sql`seat_no BETWEEN 0 AND 8`),
		check('ck_seats_stack', sql`stack >= 0`),
		check('ck_seats_bot_kind', sql`is_bot = (bot_kind IS NOT NULL)`)
	]
);

/** One hand dealt at a table. */
export const hands = pgTable(
	'hands',
	{
		id: identity('id'),
		tableId: varchar('table_id', { length: 64 }).notNull(),
		handNo: integer('hand_no').notNull(),
		button: smallint('button').notNull(),
		startedAt: now('started_at'),
		endedAt: stamp('ended_at')
	},
	(t) => [
		primaryKey({ name: 'pk_hands', columns: [t.id] }),
		foreignKey({
			name: 'fk_hands_table_id_poker_tables',
			columns: [t.tableId],
			foreignColumns: [pokerTables.id]
		}).onDelete('cascade'),
		index('ix_hands_table_id').on(t.tableId),
		unique('uq_hands_table_id_hand_no').on(t.tableId, t.handNo),
		check('ck_hands_hand_no', sql`hand_no >= 1`),
		check('ck_hands_button', sql`button BETWEEN 0 AND 8`),
		check('ck_hands_ended_at', sql`ended_at IS NULL OR ended_at >= started_at`)
	]
);

/**
 * Who played a seat in a finished hand, and what they won or lost (P4.6).
 * `playerId` is a person's id, or null for a bot. It is not a foreign key:
 * people seated before P4.1 may have no `players` row.
 */
export const handPlayers = pgTable(
	'hand_players',
	{
		handId: chips('hand_id').notNull(),
		seatNo: smallint('seat_no').notNull(),
		playerId: varchar('player_id', { length: 64 }),
		displayName: text('display_name').notNull(),
		botKind: varchar('bot_kind', { length: 64 }),
		/** Chips won (positive) or lost in the hand. */
		net: chips('net').notNull()
	},
	(t) => [
		primaryKey({ name: 'pk_hand_players', columns: [t.handId, t.seatNo] }),
		foreignKey({
			name: 'fk_hand_players_hand_id_hands',
			columns: [t.handId],
			foreignColumns: [hands.id]
		}).onDelete('cascade'),
		index('ix_hand_players_player_id').on(t.playerId),
		check('ck_hand_players_seat_no', sql`seat_no BETWEEN 0 AND 8`),
		check('ck_hand_players_bot_kind', sql`(player_id IS NULL) = (bot_kind IS NOT NULL)`)
	]
);

/** The replayable record of a finished hand, a versioned JSON document. */
export const handHistories = pgTable(
	'hand_histories',
	{
		handId: chips('hand_id').notNull(),
		format: integer('format').notNull(),
		record: jsonb('record').$type<Record<string, unknown>>().notNull(),
		createdAt: now('created_at')
	},
	(t) => [
		primaryKey({ name: 'pk_hand_histories', columns: [t.handId] }),
		foreignKey({
			name: 'fk_hand_histories_hand_id_hands',
			columns: [t.handId],
			foreignColumns: [hands.id]
		}).onDelete('cascade'),
		check('ck_hand_histories_format', sql`format >= 1`)
	]
);
