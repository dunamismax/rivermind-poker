// Builds every card file in memory, keyed by its path under web/static. The
// generator writes them and a test checks the committed files still match.
import {
	CARD_BACKS,
	CARD_RANKS,
	CARD_TREATMENTS,
	cardBackPath,
	cardFacePath
} from '../../src/lib/card-assets.ts';
import { BACK_ART } from './backs.js';
import { face } from './faces.js';

export const SUITS = ['spades', 'hearts', 'clubs', 'diamonds'];

function svg(artwork) {
	return `<svg xmlns="http://www.w3.org/2000/svg" width="168" height="232" viewBox="0 0 168 232" preserveAspectRatio="none">
<!-- RiverMind Poker card artwork. SPDX-License-Identifier: GPL-3.0-or-later. Generated by web/scripts/generate-card-art.js -->
${artwork}
</svg>
`;
}

/** @returns {Map<string, string>} SVG source for each path under web/static. */
export function renderCardSvgs() {
	const assets = new Map();
	for (const treatment of CARD_TREATMENTS) {
		for (const suit of SUITS) {
			for (const rank of CARD_RANKS) {
				const path = cardFacePath({ rank, suit }, treatment);
				const artwork = svg(face(rank, suit, treatment));
				const shared = assets.get(path);
				if (shared !== undefined && shared !== artwork) {
					throw new Error(`Conflicting artwork for shared card ${path}`);
				}
				assets.set(path, artwork);
			}
		}
	}
	for (const back of CARD_BACKS) {
		assets.set(cardBackPath(back), svg(BACK_ART[back]()));
	}
	return assets;
}
