"""Write TypeScript types from a protocol's JSON Schema.

Handles the subset of JSON Schema that the protocol modules
(`poker_ai.web.protocol`) produce:
objects, string enums, consts, arrays, maps, `anyOf`/`oneOf` unions and
`$ref`s into `$defs`. Anything else raises, so a new kind of field cannot
silently become `unknown`. The output follows the web app's Prettier style.
"""
from __future__ import annotations

import re
from typing import Any, Dict, List

SOURCES = {1: "poker_ai/web/protocol.py", 2: "rivermind/server/protocol.py"}


def header(version: int) -> str:
    flag = "" if version == 1 else f" --version {version}"
    return (
        f"// Generated by `rivermind-poker protocol-schema{flag} --typescript` from the\n"
        f"// Pydantic models in {SOURCES[version]}. Do not edit by hand.\n"
    )

_IDENTIFIER = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")


def _ref_name(ref: str) -> str:
    prefix = "#/$defs/"
    if not ref.startswith(prefix):
        raise ValueError(f"Unsupported $ref {ref!r}")
    return ref[len(prefix):]


def _literal(value: Any) -> str:
    if isinstance(value, str):
        return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    raise ValueError(f"Unsupported literal {value!r}")


def type_of(schema: Dict[str, Any]) -> str:
    """The TypeScript type for one (non-object-definition) schema."""
    if "$ref" in schema:
        return _ref_name(schema["$ref"])
    if "const" in schema:
        return _literal(schema["const"])
    if "enum" in schema:
        return " | ".join(_literal(v) for v in schema["enum"])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            return " | ".join(type_of(s) for s in schema[key])
    kind = schema.get("type")
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        item = type_of(schema["items"])
        return f"{item}[]" if _IDENTIFIER.match(item) else f"({item})[]"
    if kind == "object" and "properties" not in schema:
        value = type_of(schema.get("additionalProperties", {"type": "unknown"}))
        keys = schema.get("propertyNames")
        if keys and ("$ref" in keys or "enum" in keys):
            # Only some keys are present, e.g. the actions legal right now.
            return f"Partial<Record<{type_of(keys)}, {value}>>"
        return f"Record<string, {value}>"
    raise ValueError(f"Unsupported schema {schema!r}")


def _doc(text: str, indent: str) -> List[str]:
    lines = text.strip().splitlines()
    if len(lines) == 1:
        return [f"{indent}/** {lines[0]} */"]
    return [f"{indent}/**", *(f"{indent} * {line}".rstrip() for line in lines),
            f"{indent} */"]


def _definition(name: str, schema: Dict[str, Any]) -> List[str]:
    out = _doc(schema["description"], "") if schema.get("description") else []
    if schema.get("type") == "object" and "properties" in schema:
        required = set(schema.get("required", []))
        out.append(f"export interface {name} {{")
        for field, sub in schema["properties"].items():
            if sub.get("description"):
                out.extend(_doc(sub["description"], "\t"))
            optional = "" if field in required else "?"
            out.append(f"\t{field}{optional}: {type_of(sub)};")
        out.append("}")
    else:
        out.append(f"export type {name} = {type_of(schema)};")
    return out


def to_typescript(schema: Dict[str, Any], version: int = 1) -> str:
    """The client's types for a protocol schema (`web/src/lib/protocol.ts` for v1,
    `protocol-v2.ts` for v2)."""
    lines = [header(version)]
    if schema.get("description"):
        lines.extend(_doc(schema["description"], "") + [""])
    for name, definition in schema["$defs"].items():
        lines.extend(_definition(name, definition))
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"
